function spell(season, club, code, appointed, departed, days, matches, w, d, l, opts = {}) {
  const ppg = matches > 0 ? +((3 * w + d) / matches).toFixed(2) : 0
  return {
    season,
    club,
    code,
    clubId: opts.clubId ?? null,
    appointed,
    departed, // null = current
    days,
    matches,
    w,
    d,
    l,
    ppg: opts.ppg ?? ppg,
  }
}

function talent(name, value, debutAge, opts = {}) {
  return {
    name,
    value,
    debutAge,
    playerId: opts.playerId ?? null,
    club: opts.club ?? null,
    code: opts.code ?? null,
  }
}

